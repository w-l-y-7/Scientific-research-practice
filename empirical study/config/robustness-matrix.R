# 样本规则。**这是全项目唯一允许重新切样本的地方**，见 CLAUDE.md 第九节。
# 每一条都必须在这里声明，脚本会逐格打印样本量，reviewer-agent 会核。
#
# 用 quote() 存表达式而不是存字符串：配置即代码，拼错当场报错。
# 表达式里可以引用脚本预先派生好的辅助列（见 06_robust.R 第 4 节），
# 例如下面用到的 lpop_p90——它是按整份面板定的阈值，不随子样本漂。
SAMPLES <- list(
  full       = quote(TRUE),
  # 去掉人口最多的 10% 县。对应教程的「排除大州」：检验结论是不是被
  # 少数几个影响大的个体撑起来的。
  drop_large = quote(lpop <= lpop_p90),
  # 去掉末期（2007）。对应教程的「排除危机年份」的意图：检验结论是不是
  # 由时间轴端点驱动。mpdta 只到 2007，真正的危机年份（2008-2009）不在样本里，
  # 所以这里退一步，切的是「危机前夜」那一年——**这是与教程不同的一刀，如实标注**。
  # 写成 `<= max(year) - 1L` 而不是 `year < 2007`，是为了守住 CLAUDE.md 第九节
  # 「边界一律用 >= 和 <=」——两者在整数下等价，但统一写法省掉每次判断。
  drop_last  = quote(year <= max(year) - 1L)
  # 教程还有一档「平衡面板」。mpdta 本来就是平衡的（500 县 × 5 年），
  # 这一档在这里是空转，所以不列——列了会跑出一个和 full 完全相同的格子，
  # 让人以为做了检验，其实什么都没检验。
)

# 结果变量的构造。mpdta 只给了一个结果变量 lemp（就业的对数），
# 另外两档从它反推：
#   log   = lemp              原样
#   level = exp(lemp)         反推水平值
#   ihs   = asinh(exp(lemp))  IHS 变换（对 0 值稳健，这里用来换一种函数形式）
# **caveat**：如果 lemp 当初是按四舍五入后的就业数取的对数，exp(lemp)
# 只能近似还原原值。这一档检验的是函数形式，不是数值精度，所以可以接受；
# 但别把 exp(lemp) 当成原始就业数用。
OUTCOMES <- list(
  log   = quote(lemp),
  level = quote(exp(lemp)),
  ihs   = quote(asinh(exp(lemp)))
)

# 结果变量落到面板里用的列名。att_gt 的 yname 要字符串、feols 的公式要名字，
# 所以每个格子先算出一列再回归，不用表达式直接进模型。
